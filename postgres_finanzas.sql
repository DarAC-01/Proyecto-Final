CREATE TABLE public.cuentas_por_cobrar (
	id_cuenta int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	id_cliente_ref int4 NULL,
	monto_deuda varchar NULL,
	fecha_limite date NULL,
	estado_pago varchar NULL,
	CONSTRAINT cuentas_por_cobrar_pk PRIMARY KEY (id_cuenta)
);

CREATE TABLE public.cortes_caja (
	id_corte int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	fecha_corte date NULL,
	ingresos_totales varchar NULL,
	egresos_totales varchar NULL,
	saldo_final varchar NULL,
	CONSTRAINT cortes_caja_pk PRIMARY KEY (id_corte)
);

CREATE TABLE public.gastos_sucursal (
	id_gasto int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	concepto varchar NULL,
	monto varchar NULL,
	fecha_gasto date NULL,
	CONSTRAINT gastos_sucursal_pk PRIMARY KEY (id_gasto)
);

CREATE TABLE public.log_auditoria (
	id_log int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	usuario varchar NULL,
	modulo varchar NULL,
	accion varchar NULL,
	fecha date NULL,
	detalles varchar NULL,
	CONSTRAINT log_auditoria_pk PRIMARY KEY (id_log)
);

CREATE TABLE public.nomina_empleados (
	id_nomina int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	rfc_empleado varchar NULL,
	sueldo_pagado varchar NULL,
	fecha_pago date NULL,
	bonos varchar NULL,
	CONSTRAINT nomina_empleados_pk PRIMARY KEY (id_nomina)
);

