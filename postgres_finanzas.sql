--15. Bloquear UPDATE y DELETE en cortes_caja

CREATE OR REPLACE FUNCTION FN_Cortes_Inmutables()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'La tabla cortes_caja es inmutable por política fiscal';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_Cortes_Inmutables_Update
BEFORE UPDATE ON cortes_caja
FOR EACH ROW
EXECUTE FUNCTION FN_Cortes_Inmutables();

CREATE TRIGGER TRG_Cortes_Inmutables_Delete
BEFORE DELETE ON cortes_caja
FOR EACH ROW
EXECUTE FUNCTION FN_Cortes_Inmutables();


--16. Validar que exista la llave usuario_sistema

CREATE OR REPLACE FUNCTION FN_Valida_JSON_Auditoria()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT (NEW.detalles::jsonb ? 'usuario_sistema') THEN
        RAISE EXCEPTION 
        'El JSON de auditoría debe contener la llave usuario_sistema';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_Valida_JSON_Auditoria
BEFORE INSERT ON log_auditoria
FOR EACH ROW
EXECUTE FUNCTION FN_Valida_JSON_Auditoria();


--17. Validar sueldo mínimo

CREATE OR REPLACE FUNCTION FN_Sueldo_Justo()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.sueldo_pagado < 7500 THEN
        RAISE EXCEPTION 
        'Error: sueldo menor al salario mínimo permitido';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_Sueldo_Justo
BEFORE INSERT ON nomina_empleados
FOR EACH ROW
EXECUTE FUNCTION FN_Sueldo_Justo();


--18. Mandar NOTICE si deuda > 50000

CREATE OR REPLACE FUNCTION FN_Aviso_Deuda_Grande()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.monto_deuda > 50000 THEN
        RAISE NOTICE 
        'Aprobación de Crédito Especial Requerida';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_Aviso_Deuda_Grande
BEFORE INSERT ON cuentas_por_cobrar
FOR EACH ROW
EXECUTE FUNCTION FN_Aviso_Deuda_Grande();


--19. Bloquear deudas negativas

CREATE OR REPLACE FUNCTION FN_Deuda_Negativa()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.monto_deuda < 0 THEN
        RAISE EXCEPTION 
        'Error: no se permiten montos negativos en cuentas por cobrar';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_Deuda_Negativa
BEFORE INSERT ON cuentas_por_cobrar
FOR EACH ROW
EXECUTE FUNCTION FN_Deuda_Negativa();


